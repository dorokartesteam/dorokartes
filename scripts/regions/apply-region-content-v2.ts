async function main() {
  const source = await fs.readFile(FILE, "utf8");

  if (source.includes('"σερρεσ": {') && source.includes('"πατρα": {')) {
    console.log("PASS: region content v2 already present. No changes needed.");
    return;
  }

  const anchor = `};

export function getRegionLandingContent`;

  if (!source.includes(anchor)) {
    throw new Error("STOP: region content insertion anchor not found. File unchanged.");
  }

  const updated = source.replace(
    anchor,
    `${NEW_ENTRIES}
};

export function getRegionLandingContent`
  );

  const backup = FILE + ".before-v2";
  await fs.writeFile(backup, source, "utf8");
  await fs.writeFile(FILE, updated, "utf8");

  console.log("PASS: region landing content v2 added.");
  console.log("Backup:", path.relative(process.cwd(), backup));
  console.log("Updated:", path.relative(process.cwd(), FILE));
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
